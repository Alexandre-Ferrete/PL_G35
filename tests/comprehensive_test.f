PROGRAM COMPREHENSIVE_TEST
    INTEGER X, Y, Z
    INTEGER RESULT
    
    X = 5
    Y = 3
    
    CALL PRINT_VALUES(X, Y)
    
    RESULT = ADD_FUNCTION(X, Y)
    PRINT *, RESULT
    
    CALL SWAP(X, Y)
    PRINT *, X
    PRINT *, Y
END

INTEGER FUNCTION ADD_FUNCTION(A, B)
    INTEGER A, B
    ADD_FUNCTION = A + B
    RETURN
END

SUBROUTINE PRINT_VALUES(A, B)
    INTEGER A, B
    PRINT *, A
    PRINT *, B
END

SUBROUTINE SWAP(A, B)
    INTEGER A, B
    INTEGER TEMP
    TEMP = A
    A = B
    B = TEMP
END
